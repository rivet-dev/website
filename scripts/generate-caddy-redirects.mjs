// Generates `website/redirects.caddy` from the shared redirect map in
// `website/redirects.mjs`. The Caddyfile `import`s the emitted snippet so the
// production server returns real HTTP 301s (Astro's static redirect pages serve
// HTTP 200 with a meta-refresh, which search engines treat as soft redirects).
//
// One flat `redir` line is emitted per slash-variant of each source path. Flat
// lines (rather than a Caddy `map`) keep every rule individually auditable and
// let Caddy's case-insensitive path matchers normalize the request path.
//
// The output file is gitignored and regenerated during the Docker build.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { EXTERNAL_REDIRECT_HOST, redirects, wildcardRedirects } from '../redirects.mjs';

// Conservative charset for paths. Blocks whitespace and any character that
// could break out of a `redir` argument or inject another Caddy directive.
const SAFE_PATH = /^\/[A-Za-z0-9\-._~/]*$/;

// Absolute external targets are restricted to the single agentOS host with the
// same conservative path charset. This keeps the generator from ever emitting a
// redirect to an arbitrary host while still allowing the agentOS split-out.
const SAFE_EXTERNAL_TARGET = new RegExp(
	`^https://${EXTERNAL_REDIRECT_HOST.replace(/\./g, '\\.')}(/[A-Za-z0-9\\-._~/]*)?$`,
);

// Expands to `?query` when a query string is present, or an empty string when
// it is not, so redirects preserve query parameters (e.g. UTM tags).
const PREFIXED_QUERY = '{http.request.uri.prefixed_query}';

function assertSafe(path, kind) {
	if (typeof path !== 'string' || !SAFE_PATH.test(path)) {
		throw new Error(`unsafe ${kind} path in redirect map: ${JSON.stringify(path)}`);
	}
}

// A redirect target is valid if it is either a safe internal path or a safe
// absolute URL pointing at the allowed external host.
function assertSafeTarget(to) {
	if (typeof to !== 'string') {
		throw new Error(`unsafe target in redirect map: ${JSON.stringify(to)}`);
	}
	if (SAFE_PATH.test(to) || SAFE_EXTERNAL_TARGET.test(to)) {
		return;
	}
	throw new Error(`unsafe target in redirect map: ${JSON.stringify(to)}`);
}

// Both the bare and trailing-slash forms of a source path, deduplicated. Caddy
// path matchers are exact (no trailing `*`), so each form needs its own rule.
function sourceVariants(from) {
	const bare = from.endsWith('/') ? from.slice(0, -1) : from;
	const variants = bare === '' ? ['/'] : [bare, `${bare}/`];
	return [...new Set(variants)];
}

const lines = [
	'# Generated by scripts/generate-caddy-redirects.mjs from redirects.mjs.',
	'# Do not edit by hand. This file is gitignored and rebuilt on every deploy.',
	'',
];

for (const [from, to] of Object.entries(redirects)) {
	assertSafe(from, 'source');
	assertSafeTarget(to);
	for (const source of sourceVariants(from)) {
		lines.push(`redir ${source} ${to}${PREFIXED_QUERY} 301`);
	}
}

// Wildcard prefix redirects. Caddy matches every path under the prefix with a
// `*` path matcher.
//
// A rule whose target ends with its own source is a re-parenting: the whole
// request path is kept and only the new parent is prepended, so
// `/registry/pi` -> `/agentos/registry/pi`. Every other rule drops the captured
// suffix and collapses all sub-paths onto the target.
for (const [index, { from, to }] of wildcardRedirects.entries()) {
	assertSafe(from, 'source');
	assertSafeTarget(to);
	if (to !== from && to.endsWith(from)) {
		const parent = to.slice(0, -from.length);
		const matcher = `wildcard${index}`;
		// Preserve the suffix for re-parenting rules while normalizing both input
		// forms directly to the canonical trailing-slash destination.
		lines.push(`@${matcher}Trailing path ${from}/*/`);
		lines.push(
			`redir @${matcher}Trailing ${parent}{http.request.uri.path}${PREFIXED_QUERY} 301`,
		);
		lines.push(`@${matcher}Bare {`);
		lines.push(`\tpath ${from}/*`);
		lines.push('\tnot path */');
		lines.push('}');
		lines.push(
			`redir @${matcher}Bare ${parent}{http.request.uri.path}/${PREFIXED_QUERY} 301`,
		);
	} else {
		const target = to.endsWith('/') ? to : `${to}/`;
		lines.push(`redir ${from}/* ${target}${PREFIXED_QUERY} 301`);
	}
}

const outPath = fileURLToPath(new URL('../redirects.caddy', import.meta.url));
writeFileSync(outPath, `${lines.join('\n')}\n`);

const total = Object.keys(redirects).length + wildcardRedirects.length;
console.log(`wrote ${outPath} (${total} redirects)`);
